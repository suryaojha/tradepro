<?php
/**
 * Builds database.sql – a clean, ready-to-import schema + starter data (no users, no payments, no secrets).
 * Run from a terminal:  php make_sql.php            (output: database.sql next to this file)
 * Import with:          mysql -u root -p < database.sql      or phpMyAdmin → Import
 * For a backup WITH data use:  mysqldump -u root tradepro > backup.sql
 */
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
define('IN_INSTALL', true);
require_once __DIR__ . '/includes/bootstrap.php';

$pdo = db();
$q = fn($s) => $pdo->quote((string)$s);
$out = [];
$out[] = '-- TradePro database – schema + starter data (schema version ' . SCHEMA_VERSION . ')';
$out[] = '-- Generated by make_sql.php on ' . gmdate('Y-m-d H:i') . ' UTC. Contains NO users, trades, payments or secrets.';
$out[] = '-- Import: mysql -u root -p < database.sql   (or phpMyAdmin > Import). Safe to run on an existing database: it only creates what is missing.';
$out[] = '-- First admin: ' . DEFAULT_ADMIN_EMAIL . ' / the DEFAULT_ADMIN_PASSWORD from config.php – change it after the first login.';
$out[] = '';
$out[] = 'CREATE DATABASE IF NOT EXISTS `' . DB_NAME . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;';
$out[] = 'USE `' . DB_NAME . '`;';
$out[] = 'SET NAMES utf8mb4;';
$out[] = 'SET FOREIGN_KEY_CHECKS = 0;';
$out[] = '';

$tables = ['admins', 'users', 'wallets', 'assets', 'trades', 'transactions', 'payment_requests', 'settings', 'admin_logs', 'price_ticks',
           'password_resets', 'cg_rounds', 'cg_bets', 'mk_markets', 'mk_results', 'mk_bets', 'payout_accounts', 'kyc', 'mail_log'];
foreach ($tables as $t) {
    $row = $pdo->query('SHOW CREATE TABLE `' . $t . '`')->fetch(PDO::FETCH_NUM);
    $sql = preg_replace('/^CREATE TABLE/', 'CREATE TABLE IF NOT EXISTS', $row[1]);
    $sql = preg_replace('/ AUTO_INCREMENT=\d+/', '', $sql);
    $out[] = '-- ' . str_repeat('-', 60) . ' ' . $t;
    $out[] = $sql . ';';
    $out[] = '';
}

$out[] = '-- ------------------------------------------------------------ starter data';
// settings (defaults only; secrets and payment details stay empty)
$vals = [];
foreach (default_settings() as $k => $v) $vals[] = '(' . $q($k) . ', ' . $q($v) . ')';
$vals[] = "('cron_key', " . $q(bin2hex(random_bytes(16))) . ')';
$vals[] = "('schema_version', " . $q((string)SCHEMA_VERSION) . ')';
$out[] = 'INSERT IGNORE INTO `settings` (`k`, `v`) VALUES' . "\n  " . implode(",\n  ", $vals) . ';';
$out[] = '';

// markets
$tvs = default_tv_symbols();
$vals = [];
foreach (default_assets() as $i => [$sym, $name, $cat, $dec, , $prov, $src]) {
    $vals[] = '(' . implode(', ', [$q($sym), $q($name), $q($cat), (int)$dec, 'NULL', $q($prov), $q($src), isset($tvs[$sym]) ? $q($tvs[$sym]) : 'NULL', $i + 1]) . ')';
}
$out[] = 'INSERT IGNORE INTO `assets` (`symbol`, `name`, `category`, `decimals`, `payout_percent`, `provider`, `source_symbol`, `tv_symbol`, `sort_order`) VALUES' . "\n  " . implode(",\n  ", $vals) . ';';
$out[] = '';

// Lucky Number starter market
$out[] = "INSERT INTO `mk_markets` (`name`, `open_time`, `close_time`, `days`, `sort_order`)\nSELECT 'Kalyan', '16:45', '18:45', '1,2,3,4,5,6', 1 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM `mk_markets`);";
$out[] = '';

// first admin
$out[] = 'INSERT IGNORE INTO `admins` (`name`, `email`, `password_hash`) VALUES (' . $q(DEFAULT_ADMIN_NAME) . ', ' . $q(DEFAULT_ADMIN_EMAIL) . ', ' . $q(password_hash(DEFAULT_ADMIN_PASSWORD, PASSWORD_DEFAULT)) . ');';
$out[] = '';
$out[] = 'SET FOREIGN_KEY_CHECKS = 1;';

file_put_contents(__DIR__ . '/database.sql', implode("\n", $out) . "\n");
echo 'Wrote ' . __DIR__ . "/database.sql (" . round(filesize(__DIR__ . '/database.sql') / 1024, 1) . " KB)\n";
